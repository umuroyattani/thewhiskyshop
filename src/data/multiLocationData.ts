// Generates reproducible, realistic high-volume catalogue data with branch inventory distributions
export function generateExpandedCatalog(targetCount: number = 4200): InventoryItem[] {
  const categories = [
    "Single Malt Scotch",
    "Blended Scotch",
    "Japanese Whisky",
    "Bourbon & American",
    "Irish Whiskey",
    "Cognac & Brandy",
    "Artisanal Gin",
    "Agave & Tequila",
    "Vintage Champagne & Wine",
  ];

  const distilleries = [
    "Glenlivet", "Talisker", "Highland Park", "Dalmore", "Springbank", "Laphroaig",
    "Bowmore", "Glenmorangie", "Oban", "Aberlour", "Auchentoshan", "Bruichladdich",
    "Caol Ila", "Cardhu", "Deanston", "Glendronach", "Kilchoman", "Benriach",
    "Hakushu", "Nikka Coffey", "Kavalan", "Redbreast", "Bushmills", "WhistlePig",
    "Buffalo Trace", "Blanton's", "Eagle Rare", "E.H. Taylor", "Remy Martin",
    "Martell", "Courvoisier", "Don Julio 1942", "Fortaleza", "Hendrick's", "Tanqueray No. Ten",
  ];

  const finishes = ["Sherry Cask", "Bourbon Cask", "Port Finish", "Madeira Cask", "Virgin Oak", "Rum Cask", "Peated Oak", "Cognac Cask"];
  const ages = [10, 12, 14, 15, 16, 18, 21, 25, 30];

  const fullList: InventoryItem[] = [...BASE_INVENTORY];
  let idCounter = BASE_INVENTORY.length + 1;

  while (fullList.length < targetCount) {
    const dist = distilleries[idCounter % distilleries.length];
    const age = ages[idCounter % ages.length];
    const finish = finishes[idCounter % finishes.length];
    const cat = categories[idCounter % categories.length];
    const skuCode = `SKU-EXP-${String(idCounter).padStart(5, "0")}`;
    const basePrice = 4500 + ((idCounter * 7919) % 85000);

    // Realistic branch distribution: Kilimani (Central Hub) has high stock, others have varied
    const stockKilimani = (idCounter % 50) + 5;
    const stockCbd = (idCounter % 23);
    const stockWestlands = (idCounter % 18);
    const stockKaren = (idCounter % 12);
    const stockMombasa = (idCounter % 15);

    fullList.push({
      sku: skuCode,
      name: `${dist} ${age} Year Old ${finish}`,
      category: cat,
      subCategory: `${finish} Edition`,
      region: "Distillery Reserve",
      abv: `${40 + (idCounter % 18) * 0.5}%`,
      volume: idCounter % 3 === 0 ? "1000ml" : "700ml",
      price: Math.round(basePrice / 100) * 100,
      barcode: `501${String(1000000000 + idCounter).slice(0, 10)}`,
      image: BASE_INVENTORY[idCounter % BASE_INVENTORY.length].image,
      tastingNotes: ["Vanilla", "Oak Spice", "Orchard Fruits", "Honeyed Malt"],
      stockByBranch: {
        "loc-nbo-cbd": stockCbd,
        "loc-nbo-westlands": stockWestlands,
        "loc-nbo-kilimani": stockKilimani,
        "loc-nbo-karen": stockKaren,
        "loc-msa-central": stockMombasa,
      },
      lowStockThreshold: 4,
    });
    idCounter++;
  }

  return fullList;
}

